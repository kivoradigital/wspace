package cli_test

import (
	"testing"

	"github.com/kivoradigital/wspace/internal/domain"
	"github.com/kivoradigital/wspace/internal/ports/portstest"
)

func TestCLI_CreateAndAdd_CopyNodeModulesFlag(t *testing.T) {
	fx := newFixture(t)
	cloner := &portstest.FakeTreeCloner{FS: fx.FS}
	fx.RT.Deps.Trees = cloner
	src := domain.Path("/fixture/src/svc")
	if err := fx.FS.MkdirAll(src.Join("node_modules")); err != nil {
		t.Fatal(err)
	}
	if err := fx.FS.WriteFile(src.Join("package.json"), []byte("{}"), 0o644); err != nil {
		t.Fatal(err)
	}

	if _, stderr, code := run(fx.RT, "", "create", "plain"); code != 0 || len(cloner.Calls) != 0 {
		t.Fatalf("create without the flag: code %d stderr %q calls %v", code, stderr, cloner.Calls)
	}
	if _, stderr, code := run(fx.RT, "", "create", "ws1", "--copy-node-modules"); code != 0 || len(cloner.Calls) != 1 {
		t.Fatalf("create --copy-node-modules: code %d stderr %q calls %v", code, stderr, cloner.Calls)
	}
	if got := cloner.Calls[0]; got[1] != "/fixture/workspaces/ws1/svc/node_modules" {
		t.Fatalf("CloneTree dst = %s", got[1])
	}
}
