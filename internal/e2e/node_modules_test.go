package e2e

import (
	"encoding/json"
	"io/fs"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"testing"
)

// TestNodeModules_CopiedIntoTheWorktreeAndNotABlocker creates a workspace
// with copyNodeModules for a real Node project whose node_modules (ignored
// by its .gitignore) holds a package, an executable .bin script and a
// pnpm-style symlink: the worktree gets the same tree (link kept as a
// link, exec bit kept), on macOS through clonefile, and an unforced
// destroy is not blocked by it.
func TestNodeModules_CopiedIntoTheWorktreeAndNotABlocker(t *testing.T) {
	fx := NewFixture(t)
	workspacesRoot := filepath.Join(fx.Root, "workspaces")
	projectsRoot := filepath.Join(fx.Root, "projects")
	if err := os.MkdirAll(projectsRoot, 0o755); err != nil {
		t.Fatal(err)
	}
	web := NewGitProject(t, projectsRoot, "web", "develop")
	writeFile(t, web.Main, "package.json", "{\"name\":\"web\"}\n")
	writeFile(t, web.Main, ".gitignore", "node_modules/\n")
	runGit(t, web.Main, "add", "package.json", ".gitignore")
	runGit(t, web.Main, "commit", "-q", "-m", "node project")
	runGit(t, web.Main, "push", "-q", "origin", "develop")

	nm := filepath.Join(web.Main, "node_modules")
	for rel, body := range map[string]string{
		".pnpm/left-pad@1.0.0/node_modules/left-pad/index.js": "module.exports = 1\n",
		".bin/tool": "#!/bin/sh\necho hi\n",
	} {
		if err := os.MkdirAll(filepath.Dir(filepath.Join(nm, rel)), 0o755); err != nil {
			t.Fatal(err)
		}
		writeFile(t, nm, rel, body)
	}
	if err := os.Chmod(filepath.Join(nm, ".bin", "tool"), 0o755); err != nil {
		t.Fatal(err)
	}
	linkTarget := filepath.Join(".pnpm", "left-pad@1.0.0", "node_modules", "left-pad")
	if runtime.GOOS != "windows" {
		if err := os.Symlink(linkTarget, filepath.Join(nm, "left-pad")); err != nil {
			t.Fatal(err)
		}
	}

	responses, events := rpcSession(t, fx,
		req("ctx", "contexts.create", map[string]any{"name": "node", "workspacesRoot": workspacesRoot, "activate": true, "defaults": map[string]any{"baseBranch": "develop"}}),
		req("reg", "projects.register", map[string]any{"key": "web", "sourceDir": web.Main}),
		req("list", "projects.list", map[string]any{}),
		req("create", "workspaces.create", map[string]any{"name": "feat", "branch": "feat", "copyNodeModules": true}),
	)
	var projects []struct {
		Key            string `json:"key"`
		IsNode         bool   `json:"isNode"`
		HasNodeModules bool   `json:"hasNodeModules"`
	}
	if err := json.Unmarshal(mustResult(t, responses, "list"), &projects); err != nil || len(projects) != 1 || !projects[0].IsNode || !projects[0].HasNodeModules {
		t.Fatalf("projects.list = %+v, %v", projects, err)
	}
	mustResult(t, responses, "create")

	var copied string
	for _, ev := range events["create"] {
		if ev["key"] == "node_modules.copied" {
			copied, _ = ev["message"].(string)
		}
	}
	if copied == "" {
		t.Fatalf("no node_modules.copied event in %v", events["create"])
	}
	if runtime.GOOS == "darwin" && !strings.Contains(copied, "clonefile") {
		t.Fatalf("copied event %q: want the APFS clone path", copied)
	}

	wt := filepath.Join(workspacesRoot, "feat", "web", "node_modules")
	if data, err := os.ReadFile(filepath.Join(wt, ".pnpm", "left-pad@1.0.0", "node_modules", "left-pad", "index.js")); err != nil || string(data) != "module.exports = 1\n" {
		t.Fatalf("index.js = %q, %v", data, err)
	}
	if runtime.GOOS != "windows" {
		if info, err := os.Stat(filepath.Join(wt, ".bin", "tool")); err != nil || info.Mode().Perm()&0o111 == 0 {
			t.Fatalf(".bin/tool = %v, %v; want executable", info, err)
		}
		li, err := os.Lstat(filepath.Join(wt, "left-pad"))
		if err != nil || li.Mode()&fs.ModeSymlink == 0 {
			t.Fatalf("left-pad = %v, %v; want a symlink", li, err)
		}
		if got, _ := os.Readlink(filepath.Join(wt, "left-pad")); got != linkTarget {
			t.Fatalf("left-pad -> %q", got)
		}
	}
	// The main clone's tree is untouched.
	if _, err := os.Stat(filepath.Join(nm, ".bin", "tool")); err != nil {
		t.Fatal(err)
	}

	responses, _ = rpcSession(t, fx, req("destroy", "workspaces.destroy", map[string]any{"workspace": "feat"}))
	mustResult(t, responses, "destroy")
	if _, err := os.Stat(filepath.Join(workspacesRoot, "feat")); !os.IsNotExist(err) {
		t.Fatalf("workspace still on disk: %v", err)
	}
}
