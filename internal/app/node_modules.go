package app

import (
	"context"

	"github.com/kivoradigital/wspace/internal/domain"
	"github.com/kivoradigital/wspace/internal/messages"
	"github.com/kivoradigital/wspace/internal/ports"
)

const nodeModulesDir = "node_modules"

// NodeProjectInfo reports whether dir (a project's main clone) looks like
// a Node project — a package.json at its root — and whether it has a
// node_modules directory a new worktree could reuse.
func NodeProjectInfo(fs ports.FileSystemPort, dir domain.Path) (isNode, hasNodeModules bool) {
	if ok, _ := fs.Exists(dir.Join("package.json")); !ok {
		return false, false
	}
	has, _ := fs.IsDir(dir.Join(nodeModulesDir))
	return true, has
}

// copyNodeModules copies sourceDir/node_modules into the new worktree at
// target, so its dependencies need not be reinstalled. It only acts for a
// Node project that has node_modules, never replaces a node_modules the
// worktree already has, and uses copy-on-write where the filesystem
// allows (ports.TreeCloner). A failure is a warning, not a failed create:
// the copy is removed and the user can install dependencies as usual.
// The copy is inside the worktree, so a rollback of the worktree removes
// it too. A lockfile changed on the new branch may still need an install.
func copyNodeModules(ctx context.Context, deps Deps, sourceDir, target domain.Path, key string) {
	isNode, has := NodeProjectInfo(deps.FS, sourceDir)
	if !isNode || !has {
		return
	}
	dst := target.Join(nodeModulesDir)
	if ok, _ := deps.FS.Exists(dst); ok {
		deps.Reporter.Info(messages.NodeModulesAlreadyPresent, key)
		return
	}
	if deps.Trees == nil {
		deps.Reporter.Warn(messages.NodeModulesCopyFailed, key, "no copier available")
		return
	}
	deps.Reporter.Step(messages.NodeModulesCopying, key)
	method, err := deps.Trees.CloneTree(sourceDir.Join(nodeModulesDir), dst)
	if err != nil {
		deps.Reporter.Warn(messages.NodeModulesCopyFailed, key, err.Error())
		return
	}
	deps.Reporter.Info(messages.NodeModulesCopied, key, method)
	// git status leaves ignored files out, so an ignored node_modules is
	// never a "foreign" change blocking destroy; a tracked-nowhere,
	// unignored one would be.
	if ignored, err := deps.Git.IsIgnored(ctx, target, nodeModulesDir); err == nil && !ignored {
		deps.Reporter.Warn(messages.NodeModulesNotIgnored, key)
	}
}
