func TestRenderAdoptSummary(t *testing.T) {
	lines := app.RenderAdoptSummary(app.AdoptLegacyWorkspacesResult{
		Adopted: []app.AdoptedLegacyWorkspace{{Name: "demo", Root: "/w/demo"}},
		Skipped: []app.SkippedLegacyWorkspace{{Root: "/w/x", Reason: messages.AdoptSkipUnresolvedProject, Detail: "Nobody"}},
	})
	joined := strings.Join(lines, "\n")
	for _, want := range []string{"demo", "/w/x", "Nobody"} {
		if !strings.Contains(joined, want) {
			t.Errorf("summary %q missing %q", joined, want)
		}
	}
	if strings.Contains(joined, "%!") {
		t.Errorf("summary has a formatting error: %q", joined)
	}
	if empty := app.RenderAdoptSummary(app.AdoptLegacyWorkspacesResult{}); len(empty) != 1 {
		t.Errorf("empty summary = %q, want one 'nothing to adopt' line", empty)
	}
}

// TestAdoptLegacyWorkspaces_RecordsAPerRepoBaseWhenTheWorkspaceBaseIsAbsent:
// a repo with no branch named like the workspace base gets its own base
// recorded (the remote default here), so status compares it sensibly; a
// repo that has the workspace base records nothing.
func TestAdoptLegacyWorkspaces_RecordsAPerRepoBaseWhenTheWorkspaceBaseIsAbsent(t *testing.T) {
	f := newAdoptFixture(t)
	root := f.legacy(t, "demo", demoConf, "api", "web")
	f.git.ResolveBaseFunc = func(repo domain.Path, remote string, b domain.BranchName) (ports.BaseRef, error) {
		if repo == "/elsewhere/Some.Web" && b != "master" {
			return ports.BaseRef{Ref: "HEAD"}, nil
		}
		return ports.BaseRef{Ref: remote + "/" + string(b), Remote: true}, nil
	}
	f.git.RemoteDefaultBranchFunc = func(repo domain.Path, _ string) (domain.BranchName, bool, error) {
		return "master", true, nil
	}

	if res := f.run(t); len(res.Adopted) != 1 {
		t.Fatalf("result = %+v, want demo adopted", res)
	}

	m, err := f.store.LoadManifest(context.Background(), root)
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]domain.BranchName{}
	for _, r := range m.Workspace.Repos {
		got[r.Alias] = r.BaseBranch
	}
	if got["api"] != "" || got["web"] != "master" {
		t.Fatalf("per-repo bases = %v, want api unrecorded (has develop) and web=master", got)
	}
}

// TestAdoptLegacyWorkspaces_ExistingManifestOwnershipIsDistinguished: a
// legacy folder that already has a wspace manifest is reported as adopted
// by this context, left alone when another existing context owns it, and
// claimed when its owner context no longer exists.
func TestAdoptLegacyWorkspaces_ExistingManifestOwnershipIsDistinguished(t *testing.T) {
	f := newAdoptFixture(t)
	f.store.PutContext(f.ctx)
	f.store.PutContext(domain.Context{Name: "acme", WorkspacesRoot: adoptRoot})
	seed := func(name string, owner domain.ContextName) domain.Path {
		root := f.legacy(t, name, demoConf, "api", "web")
		f.store.PutManifest(root, domain.Manifest{SchemaVersion: 1, Workspace: domain.Workspace{Name: name, Root: root, Context: owner, Branch: "b"}})
		return root
	}
	seed("own", "work")
	seed("theirs", "acme")
	orphan := seed("findings", "legacy")

	res := f.run(t)
	if len(res.Adopted) != 0 {
		t.Fatalf("Adopted = %+v, want none", res.Adopted)
	}
	want := map[domain.Path]struct {
		reason messages.Key
		detail string
	}{
		adoptRoot.Join("own"):    {messages.AdoptSkipAlreadyAdopted, "work"},
		adoptRoot.Join("theirs"): {messages.AdoptSkipOwnedByOther, "acme"},
		orphan:                   {messages.AdoptSkipOrphanClaimed, "legacy"},
	}
	if len(res.Skipped) != len(want) {
		t.Fatalf("Skipped = %+v", res.Skipped)
	}
	for _, s := range res.Skipped {
		w := want[s.Root]
		if s.Reason != w.reason || s.Detail != w.detail {
			t.Errorf("skip %s = %s(%s), want %s(%s)", s.Root, s.Reason, s.Detail, w.reason, w.detail)
		}
		if strings.Contains(s.Message(), "%!") {
			t.Errorf("message %q", s.Message())
		}
	}
	m, _ := f.store.LoadManifest(context.Background(), orphan)
	if m.Workspace.Context != "work" || m.Workspace.Branch != "b" {
		t.Errorf("orphan manifest = %+v, want claimed by work with other fields kept", m.Workspace)
	}
	t2, _ := f.store.LoadManifest(context.Background(), adoptRoot.Join("theirs"))
	if t2.Workspace.Context != "acme" {
		t.Errorf("theirs stolen: %+v", t2.Workspace)
	}
}
