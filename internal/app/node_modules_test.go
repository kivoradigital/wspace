func TestCreateWorkspace_NeverOverwritesAWorktreeNodeModules(t *testing.T) {
	f := newNodeFixture(t)
	f.git.WorktreeAddFunc = func(_ domain.Path, spec ports.WorktreeSpec) error {
		return f.fs.MkdirAll(spec.Target.Join("node_modules"))
	}
	in := app.CreateWorkspaceInput{Context: f.ctx, Name: "ws1", Branch: "feature-x", CopyNodeModules: true, ProjectKeys: []domain.ProjectKey{"api"}}
	if _, err := app.CreateWorkspace(context.Background(), f.deps, in); err != nil {
		t.Fatal(err)
	}
	if len(f.cloner.Calls) != 0 || !hasKey(f.reporter.Infos, messages.NodeModulesAlreadyPresent) {
		t.Fatalf("calls %v infos %+v", f.cloner.Calls, f.reporter.Infos)
	}
}

