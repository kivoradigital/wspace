type nodeFixture struct {
	fs       *portstest.FakeFS
	git      *portstest.FakeGit
	store    *portstest.FakeConfigStore
	reporter *portstest.RecordingReporter
	cloner   *portstest.FakeTreeCloner
	ctx      domain.Context
	deps     app.Deps
}

// newNodeFixture: "api" is a Node project with node_modules in its main
// clone, "web" a Node project without node_modules, "go" no Node project.
func newNodeFixture(t *testing.T) *nodeFixture {
	t.Helper()
	fs := portstest.NewFakeFS(t)
	f := &nodeFixture{
		fs: fs, git: portstest.NewFakeGit(), store: portstest.NewFakeConfigStore(),
		reporter: portstest.NewRecordingReporter(),
		cloner:   &portstest.FakeTreeCloner{FS: fs, Method: ports.CloneMethodClone},
	}
	src := fs.Paths().Home.Join("src")
	f.ctx = domain.Context{
		Name: "work", WorkspacesRoot: fs.Paths().Home.Join("workspaces"),
		Projects: []domain.Project{
			{Key: "api", SourceDir: src.Join("api")},
			{Key: "web", SourceDir: src.Join("web")},
			{Key: "go", SourceDir: src.Join("go")},
		},
	}
	for _, p := range []string{"api/package.json", "api/node_modules/left-pad/index.js", "web/package.json", "go/go.mod"} {
		if err := fs.MkdirAll(parentOf(src.Join(p))); err != nil {
			t.Fatal(err)
		}
		if err := fs.WriteFile(src.Join(p), []byte("x"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	f.git.IsIgnoredFunc = func(domain.Path, string) (bool, error) { return true, nil }
	f.deps = app.Deps{Store: f.store, Git: f.git, FS: fs, Reporter: f.reporter, Trees: f.cloner}
	return f
}

func parentOf(p domain.Path) domain.Path {
	s := string(p)
	for i := len(s) - 1; i >= 0; i-- {
		if s[i] == '/' {
			return domain.Path(s[:i])
		}
	}
	return p
}

func hasKey(entries []portstest.ReportEntry, k messages.Key) bool {
	for _, e := range entries {
		if e.Key == k {
			return true
		}
	}
	return false
}

func TestNodeProjectInfo(t *testing.T) {
	f := newNodeFixture(t)
	for key, want := range map[string][2]bool{"api": {true, true}, "web": {true, false}, "go": {false, false}} {
		src := f.fs.Paths().Home.Join("src", key)
		isNode, has := app.NodeProjectInfo(f.fs, src)
		if isNode != want[0] || has != want[1] {
			t.Errorf("%s: NodeProjectInfo = %v, %v; want %v", key, isNode, has, want)
		}
	}
}

func TestCreateWorkspace_CopiesNodeModulesOnlyWhenAskedAndPresent(t *testing.T) {
	f := newNodeFixture(t)
	in := app.CreateWorkspaceInput{Context: f.ctx, Name: "ws1", Branch: "feature-x", CopyNodeModules: true}

	if _, err := app.CreateWorkspace(context.Background(), f.deps, in); err != nil {
		t.Fatal(err)
	}
	ws := f.ctx.WorkspacesRoot.Join("ws1")
	if len(f.cloner.Calls) != 1 {
		t.Fatalf("CloneTree calls = %v, want only api's", f.cloner.Calls)
	}
	got := f.cloner.Calls[0]
	if got[0] != f.fs.Paths().Home.Join("src", "api", "node_modules") || got[1] != ws.Join("api", "node_modules") {
		t.Fatalf("CloneTree(%s, %s)", got[0], got[1])
	}
	if !hasKey(f.reporter.Steps, messages.NodeModulesCopying) || !hasKey(f.reporter.Infos, messages.NodeModulesCopied) {
		t.Fatalf("steps %+v infos %+v", f.reporter.Steps, f.reporter.Infos)
	}
}

