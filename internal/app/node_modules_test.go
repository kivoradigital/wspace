// A later project's failure rolls back the whole create, copied
// node_modules included (it lives inside the removed worktree).
func TestCreateWorkspace_RollbackRemovesCopiedNodeModules(t *testing.T) {
	f := newNodeFixture(t)
	f.git.WorktreeAddFunc = func(repo domain.Path, spec ports.WorktreeSpec) error {
		if repo == f.ctx.Projects[1].SourceDir {
			return errors.New("worktree add failed")
		}
		return nil
	}
	in := app.CreateWorkspaceInput{Context: f.ctx, Name: "ws1", Branch: "feature-x", CopyNodeModules: true, ProjectKeys: []domain.ProjectKey{"api", "web"}}
	if _, err := app.CreateWorkspace(context.Background(), f.deps, in); err == nil {
		t.Fatal("CreateWorkspace succeeded")
	}
	copied := f.ctx.WorkspacesRoot.Join("ws1", "api", "node_modules", ".cloned")
	if ok, _ := f.fs.Exists(copied); ok || len(f.cloner.Calls) != 1 {
		t.Fatalf("copied node_modules survived the rollback (calls %v)", f.cloner.Calls)
	}
}

func TestAddRepo_CopiesNodeModulesWhenAsked(t *testing.T) {
	f := newNodeFixture(t)
	if _, err := app.CreateWorkspace(context.Background(), f.deps, app.CreateWorkspaceInput{Context: f.ctx, Name: "ws1", Branch: "feature-x", ProjectKeys: []domain.ProjectKey{"go"}}); err != nil {
		t.Fatal(err)
	}
	root := f.ctx.WorkspacesRoot.Join("ws1")
	if _, err := app.AddRepo(context.Background(), f.deps, app.AddRepoInput{WorkspaceRoot: root, Context: f.ctx, ProjectKey: "api", CopyNodeModules: true}); err != nil {
		t.Fatal(err)
	}
	if len(f.cloner.Calls) != 1 || f.cloner.Calls[0][1] != root.Join("api", "node_modules") {
		t.Fatalf("calls %v", f.cloner.Calls)
	}
}
