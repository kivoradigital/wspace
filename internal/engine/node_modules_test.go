func seedNodeProject(t *testing.T, f *fixture) {
	t.Helper()
	api := f.ctx.Projects[0].SourceDir
	if err := f.fs.MkdirAll(api.Join("node_modules", "x")); err != nil {
		t.Fatal(err)
	}
	if err := f.fs.WriteFile(api.Join("package.json"), []byte("{}"), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestListProjects_ReportsNodeProjects(t *testing.T) {
	f := newFixture(t)
	seedNodeProject(t, f)

	list, err := f.eng.ListProjects(context.Background(), engine.ProjectsRef{})
	if err != nil {
		t.Fatal(err)
	}
	if !list[0].IsNode || !list[0].HasNodeModules || list[1].IsNode || list[1].HasNodeModules {
		t.Fatalf("projects = %+v", list)
	}
	c, err := f.eng.GetContext(context.Background(), engine.ContextRef{})
	if err != nil || !c.Projects[0].HasNodeModules || c.Projects[1].IsNode {
		t.Fatalf("contexts.get projects = %+v, %v", c.Projects, err)
	}
}

func TestCreateWorkspaceAndAddRepo_CopyNodeModulesWhenAsked(t *testing.T) {
	f := newFixture(t)
	seedNodeProject(t, f)
	cloner := &portstest.FakeTreeCloner{FS: f.fs}
	f.eng = engine.New(engine.Deps{Store: f.store, Git: f.git, FS: f.fs, Checker: portstest.NewFakeReleaseChecker(), Version: "1.2.3", Trees: cloner})
	ctx := context.Background()

	if _, err := f.eng.CreateWorkspace(ctx, engine.CreateWorkspaceParams{Name: "ws1", Projects: []string{"web"}, CopyNodeModules: true}, nil); err != nil {
		t.Fatal(err)
	}
	if len(cloner.Calls) != 0 {
		t.Fatalf("calls = %v (web is not a Node project)", cloner.Calls)
	}
	if _, err := f.eng.AddRepo(ctx, engine.AddRepoParams{Workspace: "ws1", Project: "api", CopyNodeModules: true}, nil); err != nil {
		t.Fatal(err)
	}
	if len(cloner.Calls) != 1 || cloner.Calls[0][1] != f.ctx.WorkspacesRoot.Join("ws1", "api", "node_modules") {
		t.Fatalf("calls = %v", cloner.Calls)
	}
	addable, err := f.eng.AddableProjects(ctx, engine.WorkspaceRef{Workspace: "ws1"})
	if err != nil || len(addable) != 0 {
		t.Fatalf("addable = %+v, %v", addable, err)
	}
}
